// Raw field 2 values exercise int32's low-32-bit signed interpretation, not
// merely the normal typed producer's -1 sentinel. Generated by Go protowire.
func credentialWireFixtures() map[string][]byte {
	raws := map[string]uint64{
		"wire_zero": 0, "wire_high_bit": 0x80000000, "wire_low32_negative": 0xffffffff,
		"wire_wrap_zero": 0x100000000, "wire_wrap_one": 0x100000001,
		"wire_wrap_negative": 0x180000000, "wire_canonical_negative": 0xffffffffffffffff,
	}
	fixtures := make(map[string][]byte, len(raws))
	for name, raw := range raws {
		data := protowire.AppendTag(nil, 1, protowire.BytesType)
		data = protowire.AppendString(data, interopJobID)
		data = protowire.AppendTag(data, 2, protowire.VarintType)
		fixtures[name] = protowire.AppendVarint(data, raw)
	}
	return fixtures
}

func TestAgentProducedInteropFixtures(t *testing.T) {
	fixtures := interopFixtures(t, "go_messages")
	for name, message := range agentInteropMessages() {
		t.Run(name, func(t *testing.T) {
			actual, err := (proto.MarshalOptions{Deterministic: true}).Marshal(message)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(actual, interopBytes(t, fixtures, name)) {
				t.Fatal("Go producer changed; regenerate peer fixture from these source values")
			}
		})
	}
	for name, wire := range credentialWireFixtures() {
		if !bytes.Equal(wire, interopBytes(t, fixtures, name)) {
			t.Fatalf("wire fixture %s changed", name)
		}
	}
}

func TestCredentialProbeInt32Interop(t *testing.T) {
	fixtures := interopFixtures(t, "go_messages")
	for name, expected := range map[string]int32{
		"wire_zero": 0, "wire_high_bit": -2147483648, "wire_low32_negative": -1,
		"wire_wrap_zero": 0, "wire_wrap_one": 1, "wire_wrap_negative": -2147483648,
		"wire_canonical_negative": -1,
	} {
		t.Run(name, func(t *testing.T) {
			var result pb.CredentialProbeResult
			if err := proto.Unmarshal(interopBytes(t, fixtures, name), &result); err != nil {
				t.Fatal(err)
			}
			if result.GetMatchedIndex() != expected || result.GetProbeId() != interopJobID {
				t.Fatalf("decoded %v, want index %d", &result, expected)
			}
		})
	}
}

func TestServerProducedInteropFixtures(t *testing.T) {
	// Actual Elixir producer: Towerops.Proto.Encode, with the source structs in
	// towerops-web/test/towerops/proto/interop_test.exs server_messages/0.
	// This consumer asserts full message semantics, including absence/defaults,
	// rather than comparing schemas or round-tripping through a local encoder.
	fixtures := interopFixtures(t, "elixir_messages")
	for name, expected := range serverInteropMessages() {
		t.Run(name, func(t *testing.T) {
			actual := expected.ProtoReflect().New().Interface()
			if err := proto.Unmarshal(interopBytes(t, fixtures, name), actual); err != nil {
				t.Fatal(err)
			}
			if !proto.Equal(actual, expected) {
				t.Fatalf("decoded %v\nwant %v", actual, expected)
			}
		})
	}
}

