func interopFixtures(t *testing.T, name string) map[string]string {
	t.Helper()
	data, err := os.ReadFile("testdata/" + name + ".json")
	if err != nil {
		t.Fatal(err)
	}
	var fixtures map[string]string
	if err := json.Unmarshal(data, &fixtures); err != nil {
		t.Fatal(err)
	}
	return fixtures
}

func interopBytes(t *testing.T, fixtures map[string]string, name string) []byte {
	t.Helper()
	encoded, ok := fixtures[name]
	if !ok {
		t.Fatalf("missing fixture %s", name)
	}
	data, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

